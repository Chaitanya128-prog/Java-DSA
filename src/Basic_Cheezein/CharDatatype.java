package Basic_Cheezein;

public class CharDatatype {
    public static void main(String[] args) {
     char chinu = 'a';
     System.out.println(chinu);
     char eva = 'e';
     System.out.println(eva);
     char amir = '%';
     System.out.println(amir);
     char mommy = '7';  //Here 7 is a character not a number (0-9),(a-z),(A-Z),(!,@,#,$,%,^,&,*,(,))
     System.out.println(mommy);
     //Ascii of a=97,z=122,A=65,Z=90,0=48,9=57
    }
}
